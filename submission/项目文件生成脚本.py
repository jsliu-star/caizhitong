def _font(run, name=SONG, size=12, bold=False, color=INK, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = color
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run._element.rPr.rFonts.set(qn('w:ascii'), name)
    run._element.rPr.rFonts.set(qn('w:hAnsi'), name)

def _para(align=WD_ALIGN_PARAGRAPH.LEFT, before=0, after=0, spacing=1.5,
          indent_first=0, indent_left=0, keep=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = align
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    if spacing:
        pf.line_spacing = spacing
    if indent_first:
        pf.first_line_indent = Pt(indent_first)
    if indent_left:
        pf.left_indent = Cm(indent_left)
    pf.keep_with_next = keep
    return p

