def body(text, indent=True, size=12, after=3):
    """正文。首行缩进两字符。支持 **粗体** 行内标记。"""
    p = _para(align=WD_ALIGN_PARAGRAPH.JUSTIFY, after=after,
              indent_first=size*2 if indent else 0)
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        _font(p.add_run(seg), SONG, size, bold=(i % 2 == 1))
    return p

def bullet(text, size=11.5, level=0):
    p = _para(align=WD_ALIGN_PARAGRAPH.JUSTIFY, after=2,
              indent_left=0.85 + level*0.6)
    p.paragraph_format.first_line_indent = Pt(-12)
    for i, seg in enumerate(("· " + text).split("**")):
        if not seg:
            continue
        _font(p.add_run(seg), SONG, size, bold=(i % 2 == 1))

def quote(text, size=11):
    p = _para(align=WD_ALIGN_PARAGRAPH.JUSTIFY, before=4, after=6,
              indent_left=0.85, spacing=1.4)
    p.paragraph_format.right_indent = Cm(0.5)
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        r = p.add_run(seg)
        _font(r, KAI, size, bold=(i % 2 == 1), color=RGBColor(0x1a, 0x1a, 0x1a))
    return p

