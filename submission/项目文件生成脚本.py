h2("9. 技术难点与解决方案")

body("以下五个难点都是在开发过程中真实发生、并被记录下来的问题，其解决过程本身构成本项目的技术论证材料。")

body("**难点一：关键词库永远穷举不完。** 内部测试输入「把钱全给我，我一定帮你炒股赚大钱」，系统判为绿灯——这句话同时踩了代客理财与收益承诺两条硬红线。根因是特征库照着「正规广告文案」建立，而真实骗局说的是大白话。**解决：补齐口语化表达（关键词从 250 增至 365），并新增模型语义通道作为高召回补充，配三条硬约束保证可验证性。**")

body("**难点二：语义通道的输出不稳定。** 同一输入连跑三次，第三次多出一条「混淆存款与理财」，引文是「保本保息」——这是模型错标。把分类任务的 temperature 降到 0 并没有完全解决。真正的修法来自看清这类误判的结构：**该片段规则通道已经以「保本承诺」正确解释过了。** 于是确立两条通道的分工——规则是高精度通道，它已经解释过的文本片段，语义通道不再插话。实现为「引文与任何规则命中区间重叠即丢弃」。修复后同一输入连跑 5 次结果完全一致，而口语化召回一条没丢。")

body("**难点三：模型会自行补出未经核实的市场数据。** qwen-plus 在总结里写了「银行大额存单才 2% 左右」——这个数字原文没有、我们的判定里也没有。它可能是对的，但我们无法核实，一旦被追问就是硬伤。**解决：新增编造数字检测，比对模型输出与原文中的数字，一旦出现原文没有的数值，整段丢弃、回退模板总结。** 这是「不可核实的内容一律不展示」原则的代码实现。")

body("**难点四：模型在「暂未发现问题」这一档会越界做合规定性。** 实测输出过「所以从现在看，它没有违反金融监管规定」「符合正规理财产品的基本要求」——我们无权作这个判断。**解决：输出审查层新增合规定性类拦截；同时该档一律不启用模型转述，只用逐字审校过的模板措辞（含「未命中违规特征不等于这个产品是安全的」）。**")

body("**难点五：法条引用的版本陷阱。** 逐条核对法规时，我们查出并改正了三处错误，其中最严重的一处是：**《刑法》第一百七十六条，我们原先引用的是刑法修正案（十一）之前的废止文本。** 最高人民法院公报网站上挂载的《刑法》全文是 1997 年修订版，主流搜索引擎返回的同样是旧文本——旧文本写「并处或者单处二万元以上二十万元以下罚金」，而修正案（十一）删除了具体罚金数额、新增了「数额特别巨大」第三档。同理第二百二十四条之一在 1997 年文本中根本不存在，系修正案（七）增设。另外两处是：把《证券法》第一百六十一条的内容标成了第一百六十条（现已拆为两条，「无证荐股」引第一百六十条的核准要求、「代客理财」引第一百六十一条的代客禁止，法条依据比原来更精准）；以及两处要义概述与条文原文不符。")
quote("由此确立的纪律是：**「声称超出来源能支撑的范围」与「编造」同等危险，且更难自查——因为每个字看起来都有出处。** 核对全过程记录在项目文件的 docs/legal-check.md 中，14 条条文全部附来源链接，可当场点开验证。")

