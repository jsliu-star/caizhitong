def image(path, caption, width_cm=None, max_h_cm=17.0):
    im = Image.open(path)
    w, h = im.size
    wc = width_cm or CONTENT_W
    hc = wc * h / w
    if hc > max_h_cm:
        hc = max_h_cm
        wc = hc * w / h
    p = _para(align=WD_ALIGN_PARAGRAPH.CENTER, before=8, after=2, spacing=1.0)
    p.add_run().add_picture(path, width=Cm(wc))
    c = _para(align=WD_ALIGN_PARAGRAPH.CENTER, after=10, spacing=1.2)
    _font(c.add_run(caption), HEI, 9.5, color=MUTE)

def table(headers, rows, widths=None, size=10, head_size=10):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
